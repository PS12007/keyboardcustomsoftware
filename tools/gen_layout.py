"""Generate src/layout_data.rs from tools/keymap.json (the key-by-key mapping).

Run: python tools/gen_layout.py
"""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)

# Each row: list of (keymap name, id, label, width in key units, Windows virtual-key code)
# or ("gap", width). Row y: F-row = 0, then 1.25, 2.25, ...
ROWS = [
    [("escape", "esc", "Esc", 1, 0x1B), ("gap", .25),
     ("f1", "f1", "F1", 1, 0x70), ("f2", "f2", "F2", 1, 0x71), ("f3", "f3", "F3", 1, 0x72), ("f4", "f4", "F4", 1, 0x73), ("gap", .25),
     ("f5", "f5", "F5", 1, 0x74), ("f6", "f6", "F6", 1, 0x75), ("f7", "f7", "F7", 1, 0x76), ("f8", "f8", "F8", 1, 0x77), ("gap", .25),
     ("f9", "f9", "F9", 1, 0x78), ("f10", "f10", "F10", 1, 0x79), ("f11", "f11", "F11", 1, 0x7A), ("f12", "f12", "F12", 1, 0x7B), ("gap", .25),
     ("delete", "del", "Del", 1, 0x2E)],
    [("` ~ recording key left of number 1", "grave", "`", 1, 0xC0)]
    + [(str(n), str(n), str(n), 1, 0x30 + n) for n in range(1, 10)]
    + [("0", "0", "0", 1, 0x30), ("- _", "minus", "-", 1, 0xBD), ("= +", "equal", "=", 1, 0xBB),
       ("back space", "backspace", "Bksp", 2, 0x08), ("gap", .25), ("home / ins", "home", "Home", 1, 0x24)],
    [("tab", "tab", "Tab", 1.5, 0x09)]
    + [(c, c, c.upper(), 1, ord(c.upper())) for c in "qwertyuiop"]
    + [("[ {", "lbracket", "[", 1, 0xDB), ("] }", "rbracket", "]", 1, 0xDD), ("\\ |", "backslash", "\\", 1.5, 0xDC),
       ("gap", .25), ("pageup /printscreen", "pgup", "PgUp", 1, 0x21)],
    [("caps lock", "caps", "Caps", 1.75, 0x14)]
    + [(c, c, c.upper(), 1, ord(c.upper())) for c in "asdfghjkl"]
    + [(";", "semicolon", ";", 1, 0xBA), ("' \"", "quote", "'", 1, 0xDE), ("enter", "enter", "Enter", 2.25, 0x0D),
       ("gap", .25), ("page down / pause", "pgdn", "PgDn", 1, 0x22)],
    [("left shift", "lshift", "Shift", 2.25, 0xA0)]
    + [(c, c, c.upper(), 1, ord(c.upper())) for c in "zxcvbnm"]
    + [(", <", "comma", ",", 1, 0xBC), (".", "period", ".", 1, 0xBE), ("/ ?", "slash", "/", 1, 0xBF),
       ("right shift", "rshift", "Shift", 1.75, 0xA1), ("gap", .25), ("up arrow", "up", "", 1, 0x26), ("end", "end", "End", 1, 0x23)],
    [("left control", "lctrl", "Ctrl", 1.25, 0xA2), ("windows key", "win", "Win", 1.25, 0x5B), ("left alt", "lalt", "Alt", 1.25, 0xA4),
     ("space", "space", "", 6.25, 0x20), ("right alt", "ralt", "Alt", 1, 0xA5), ("fn", "fn", "Fn", 1, 0),
     ("right control", "rctrl", "Ctrl", 1, 0xA3), ("gap", .25),
     ("left arrow", "left", "", 1, 0x25), ("down arrow", "down", "", 1, 0x28), ("right arrow", "right", "", 1, 0x27)],
]
ROW_Y = [0, 1.25, 2.25, 3.25, 4.25, 5.25]

# Fn-layer keys share an LED with another key
EXTRA_VK = {0x2D: "home", 0x2C: "pgup", 0x13: "pgdn"}  # Insert, PrintScreen, Pause


def main():
    with open(os.path.join(HERE, "keymap.json")) as f:
        keymap = json.load(f)
    name_to_slot = {v: int(k) for k, v in keymap.items() if v != "none"}
    hidden = sorted(int(k) for k, v in keymap.items() if v == "none")

    keys = []
    for r, row in enumerate(ROWS):
        x = 0.0
        for item in row:
            if item[0] == "gap":
                x += item[1]
                continue
            name, kid, label, w, vk = item
            keys.append((kid, label, x, w, ROW_Y[r], r, name_to_slot.pop(name), vk))
            x += w
    assert not name_to_slot, f"unplaced keys: {name_to_slot}"

    lines = [
        "// Generated by tools/gen_layout.py from tools/keymap.json. Do not edit by hand.",
        "use crate::layout::Key;",
        "",
        "pub const KEYS: &[Key] = &[",
    ]
    for kid, label, x, w, y, r, slot, vk in keys:
        lab = label.replace("\\", "\\\\")
        lines.append(f'    Key {{ id: "{kid}", label: "{lab}", x: {x:.3f}, y: {y:.2f}, w: {w:.2f}, row: {r}, slot: {slot}, vk: 0x{vk:02X} }},')
    lines.append("];")
    lines.append("")
    lines.append("/// LED slots that are not under a visible key (likely edge/under-case LEDs).")
    lines.append("#[allow(dead_code)]")
    lines.append(f"pub const HIDDEN_SLOTS: &[u8] = &{hidden};")
    lines.append("")
    lines.append("/// Extra virtual-key codes that light an existing key (Fn layer).")
    lines.append("pub const EXTRA_VK: &[(u16, &str)] = &[" + ", ".join(f'(0x{vk:02X}, "{k}")' for vk, k in EXTRA_VK.items()) + "];")
    out = os.path.join(ROOT, "src", "layout_data.rs")
    os.makedirs(os.path.dirname(out), exist_ok=True)
    with open(out, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print(f"wrote {len(keys)} keys to {out}")


if __name__ == "__main__":
    main()
